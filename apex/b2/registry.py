def _validate_registry() -> None:
    """Enforce the budget and the anti-double-counting invariants at import time."""
    if len(VOTING_FAMILIES) > VOTING_BUDGET:
        raise ValueError(
            f"Voting budget exceeded: {len(VOTING_FAMILIES)} families declared, "
            f"budget is {VOTING_BUDGET}. Adding a family must displace one."
        )

    keys = [f.key for f in VOTING_FAMILIES]
    if len(set(keys)) != len(keys):
        raise ValueError("Duplicate voting family keys")

    # Every voting member must declare a scale and a frequency. Enforced here
    # as well as in __post_init__ so the invariant holds for the registry as a
    # whole and not merely one definition at a time.
    for family in VOTING_FAMILIES:
        for spec in family.member_specs:
            if spec.threshold <= 0.0:
                raise ValueError(
                    f"{family.key}.{spec.key}: a neutral band must be positive. "
                    "A zero band makes every non-zero reading directional."
                )
            if spec.scale is MemberScale.STANDARDISED_SIGMA and spec.threshold < 0.1:
                raise ValueError(
                    f"{family.key}.{spec.key}: a standardised-sigma member may not "
                    f"use a neutral band of {spec.threshold} sigma. A band this "
                    "small classifies ordinary noise as directional evidence, "
                    "which is the defect MemberScale was introduced to prevent."
                )

    # A member may belong to exactly one family. This is the structural guard
    # against the same evidence being counted twice under two labels.
    seen: dict[str, str] = {}
    for family in VOTING_FAMILIES:
        for member in family.members:
            if member in seen:
                raise ValueError(
                    f"Member {member!r} appears in both {seen[member]!r} and "
                    f"{family.key!r}; a member may belong to exactly one family."
                )
            seen[member] = family.key

    inactive_keys = [c.key for c in ACTIVE_NON_VOTING_COMPONENTS + DORMANT_COMPONENTS + WITHHELD_COMPONENTS]
    if len(set(inactive_keys)) != len(inactive_keys):
        raise ValueError("Duplicate inactive component keys")

    overlap = set(inactive_keys) & set(keys)
    if overlap:
        raise ValueError(f"Components cannot be both voting and inactive: {sorted(overlap)}")

    for component in DORMANT_COMPONENTS:
        if component.role is not Role.DORMANT:
            raise ValueError(f"{component.key}: dormant components must have role DORMANT")

    if not CRITICAL_FAMILY_KEYS <= set(keys):
        raise ValueError("CRITICAL_FAMILY_KEYS references an undeclared family")

    # H3: an UNOBTAINABLE member is excluded from the coverage denominator
    # forever, so the reason has to be on the record rather than in someone's
    # head. Without this, "unobtainable" becomes a way to quietly delete an
    # inconvenient member from the measure of completeness.
    for family in VOTING_FAMILIES:
        for spec in family.member_specs:
            if (
                spec.expectation is EvidenceExpectation.UNOBTAINABLE
                and not spec.frequency_basis.strip()
            ):
                raise ValueError(
                    f"{family.key}.{spec.key}: a member declared UNOBTAINABLE must "
                    "record why in frequency_basis. It is removed from the Data "
                    "Confidence denominator permanently, and an unexplained "
                    "removal is indistinguishable from hiding a data gap."
                )

    # H3: every canonical macro family must be accounted for somewhere in this
    # registry. A key that is neither voting nor dormant would make the
    # architectural completeness cap silently under-report -- the family would
    # be absent from the system AND absent from the list of things noted as
    # absent, which is the exact failure the cap exists to prevent.
    unaccounted = CANONICAL_MACRO_FAMILY_KEYS - (set(keys) | set(inactive_keys))
    if unaccounted:
        raise ValueError(
            f"CANONICAL_MACRO_FAMILY_KEYS entries {sorted(unaccounted)} are neither "
            "declared as voting families nor registered as inactive components. A "
            "canonical macro family must be visible in the registry either way."
        )

    module_keys = [m.key for m in ASSET_MODULES]
    if len(set(module_keys)) != len(module_keys):
        raise ValueError("Duplicate asset module keys")
    # An asset module must never share an identity with a voting family or with
    # an inactive component: they are different roles with different rules.
    clash = set(module_keys) & (set(keys) | set(inactive_keys))
    if clash:
        raise ValueError(f"Asset modules clash with existing components: {sorted(clash)}")


_validate_registry()


