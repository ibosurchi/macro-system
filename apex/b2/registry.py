class MemberScale(Enum):
    """The numeric scale a member signal actually lives on.

    A flat/neutral threshold is only meaningful relative to a scale, and this
    project holds members on two genuinely different ones. Declaring the scale
    is what stops a threshold chosen for one from being applied to the other --
    which is exactly the defect this enum was introduced to close.

    ``BOUNDED_UNIT``
        A score already squashed onto [-1, 1], where 1.0 is the maximum the
        producing function can emit. Every ``calc_mtf`` score and every rescaled
        news-points reading is of this kind. Here "0.05" means five percent of
        full scale, which is the sense the existing project convention intended.

    ``STANDARDISED_SIGMA``
        A z-score: an observation divided by its own noise scale, unbounded, and
        where 1.0 means "a one-standard-deviation move" rather than "the maximum
        possible". A threshold of 0.05 on this scale means five hundredths of a
        standard deviation, which is noise, not evidence.

    ``CATEGORICAL_UNIT``
        A member that only ever emits an exact member of {-1.0, 0.0, +1.0}.
        Any threshold strictly between 0 and 1 behaves identically.
    """

    BOUNDED_UNIT = "bounded_unit"
    STANDARDISED_SIGMA = "standardised_sigma"
    CATEGORICAL_UNIT = "categorical_unit"


#: Neutral band for a member on the BOUNDED_UNIT scale.
#:
#: NOT a new number: this is the 0.05 "flat vote" cutoff the project already
#: uses in ``_gold_evidence_conflict_diagnostics``, retained unchanged for the
#: scale it was actually chosen for.
BOUNDED_UNIT_FLAT_THRESHOLD = 0.05

#: Neutral band for a member on the STANDARDISED_SIGMA scale, in sigma.
#:
#: NOT a new number either, and deliberately not tuned. It is
#: ``ValidationConfig.neutral_band_atr_multiple`` -- the k the validation layer
#: already uses, with the same sqrt-time scaling, to decide whether a REALISED
#: move escaped the noise band and may therefore carry a verdict.
#:
#: Using one k on both sides is a coherence requirement rather than a
#: preference. If the validation layer would score a 0.4-sigma outcome as
#: NEUTRAL -- "the market did not go anywhere" -- then the evidence layer must
#: not read a 0.4-sigma input as directional and claim the market is going
#: somewhere. The two halves of the system have to agree about what counts as
#: noise, or a claim can be generated by evidence its own resolution would
#: refuse to score.
#:
#: This is a NOISE FLOOR, not a calibration. It is deliberately the smallest
#: value with an existing justification in this repository, and it is left
#: injectable so the null benchmark can vary it as a research control. Raising
#: it because it improves a hit rate would be calibration, which is withheld.
STANDARDISED_SIGMA_FLAT_THRESHOLD = 0.5

#: Neutral band for CATEGORICAL_UNIT members. Any value in (0, 1) is
#: equivalent; the bounded-unit constant is reused rather than adding a third.
CATEGORICAL_UNIT_FLAT_THRESHOLD = BOUNDED_UNIT_FLAT_THRESHOLD

_DEFAULT_THRESHOLD_BY_SCALE: Mapping[MemberScale, float] = {
    MemberScale.BOUNDED_UNIT: BOUNDED_UNIT_FLAT_THRESHOLD,
    MemberScale.STANDARDISED_SIGMA: STANDARDISED_SIGMA_FLAT_THRESHOLD,
    MemberScale.CATEGORICAL_UNIT: CATEGORICAL_UNIT_FLAT_THRESHOLD,
}


class EvidenceExpectation(Enum):
    """Whether the architecture EXPECTS this member to carry evidence.

    This is the H3 mechanism. Data Confidence previously asked only "did this
    family speak?", which is a boolean over five families and is satisfied by a
    single surviving member. It could therefore report HIGH with five of fifteen
    declared member signals present. Coverage needs a denominator, and a
    denominator is only meaningful once each member declares whether its absence
    is a data deficiency at all.

    The classes are CATEGORICAL on purpose. A numeric importance weight would be
    an uncalibrated free parameter chosen before the corpus that could justify
    it exists -- the same objection that keeps ``ConfidenceLevel`` categorical.

    ``REQUIRED``
        Absence makes the evaluation uninformative. Counted in the denominator.
        **No production member currently declares this**: "required" is already
        expressed at family granularity by ``CRITICAL_FAMILY_KEYS``, and
        duplicating that policy at member level is not a change H3 was approved
        to make. It is declared here because the taxonomy is incomplete without
        it and because a future family may genuinely need it. Note that it does
        NOT create a path to LOW -- see ``EXPECTED`` below.

    ``EXPECTED``
        Should normally arrive; its absence is a real degradation of coverage.
        Counted in the denominator.

        REQUIRED and EXPECTED are treated identically by the coverage ratio.
        That is deliberate: H3 is bound by invariant I-1, which forbids any new
        route to ``ConfidenceLevel.LOW``. The only conditions that may reach LOW
        are the pre-existing ones (a critical family unavailable, two or more
        families unavailable, a BROKEN series). Coverage floors at MODERATE, so
        a REQUIRED member that is missing degrades coverage and is named in the
        provenance block, but it cannot by itself degrade the decision.

    ``OPTIONAL``
        Its absence is not a data deficiency. Excluded from the denominator
        entirely, so it can neither raise nor lower coverage.

    ``UNOBTAINABLE``
        Declared, and never obtainable in this project. Excluded from the
        denominator. Without this class the two permanently-null Structure
        members would cap every record ever written, which is a constant offset
        carrying no information rather than a measurement. A member declaring
        this MUST record why in ``frequency_basis``; the validator enforces it.
    """

    REQUIRED = "required"
    EXPECTED = "expected"
    OPTIONAL = "optional"
    UNOBTAINABLE = "unobtainable"

    @property
    def is_counted(self) -> bool:
        """True when this member belongs in the coverage denominator."""
        return self in (EvidenceExpectation.REQUIRED, EvidenceExpectation.EXPECTED)


#: Bumped when the MEANING of an expectation assignment changes -- a member
#: reclassified, a class redefined, a new class added. Stored on every record
#: alongside the coverage basis so a historical Data Confidence value stays
#: explicable if these declarations are ever revised.
EXPECTATION_VERSION = "b2-evidence-expectation-v1"


@dataclass(frozen=True)
class MemberSpec:
    """What one family member IS, as opposed to what it read this evaluation.

    Three facts live here and all three are structural rather than incidental:

    *   ``scale`` + ``flat_threshold`` -- the neutral band, expressed in the
        member's own units. Without this a single package constant gets applied
        to quantities that do not share a scale.
    *   ``frequency`` -- the natural publication cadence of the slowest series
        behind the member. This is what ``horizons.horizon_compatible`` needs in
        order to refuse a member that is too slow to be evidence at a given
        decision horizon.
    *   ``expectation`` -- whether the absence of this member is a data
        deficiency. This is what gives the H3 coverage ratio a denominator that
        is DECLARED rather than discovered from whatever happened to arrive.

    ``frequency`` is deliberately the SLOWEST constituent series, not an
    average. A member blended from a monthly and a quarterly release cannot
    update faster than its quarterly leg, and treating it as though it could is
    the frequency smuggling this field exists to prevent.

    ``expectation`` defaults to ``EXPECTED``, which keeps every pre-H3
    construction of this dataclass valid -- including
    ``dataclasses.replace(spec, flat_threshold=...)`` in the null benchmark --
    and defaults in the direction that COUNTS a member rather than silently
    excusing it.
    """

    key: str
    scale: MemberScale
    frequency: SeriesFrequency
    #: Source note recording where ``frequency`` came from, so a later reader
    #: can check it against the production series configuration rather than
    #: trusting it.
    frequency_basis: str = ""
    flat_threshold: float | None = None
    #: Whether the architecture expects evidence here. See EvidenceExpectation.
    expectation: EvidenceExpectation = EvidenceExpectation.EXPECTED

    @property
    def threshold(self) -> float:
        """The neutral band for this member, defaulted from its scale."""
        if self.flat_threshold is not None:
            return float(self.flat_threshold)
        return _DEFAULT_THRESHOLD_BY_SCALE[self.scale]

    def as_record(self) -> dict[str, object]:
        return {
            "member": self.key,
            "scale": self.scale.value,
            "frequency": self.frequency.label,
            "frequency_period_days": float(self.frequency.period_days),
            "flat_threshold": float(self.threshold),
            "frequency_basis": self.frequency_basis,
            # H3: the declared expectation, so a stored Data Confidence value
            # can be re-derived without consulting repository history.
            "expectation": self.expectation.value,
        }


@dataclass(frozen=True)
class FamilyDefinition:
    """A voting family. Membership is frozen and must not be tuned against results."""

    key: str
    label: str
    role: Role
    horizon: Horizon
    members: tuple[str, ...]
    justification: str
    data_sources: tuple[str, ...]
    #: One spec per declared member, in the same order. Carries the member's
    #: scale, its neutral band and the cadence of the slowest series behind it.
    #: Required: a member with no declared scale cannot be classified safely,
    #: and a member with no declared frequency cannot be horizon-checked.
    member_specs: tuple[MemberSpec, ...] = ()

    def __post_init__(self) -> None:
        if self.role is not Role.ACTIVE_VOTING:
            raise ValueError(f"{self.key}: a voting family must have role ACTIVE_VOTING")
        if not self.members:
            raise ValueError(f"{self.key}: a voting family must declare at least one member")
        if len(set(self.members)) != len(self.members):
            raise ValueError(f"{self.key}: duplicate member keys")
        spec_keys = tuple(s.key for s in self.member_specs)
        if spec_keys != self.members:
            raise ValueError(
                f"{self.key}: member_specs {list(spec_keys)} must cover exactly the "
                f"declared members {list(self.members)}, in the same order. A member "
                "with no declared scale and frequency cannot be classified or "
                "horizon-checked, and silently defaulting either one is how a "
                "threshold meant for another scale gets applied."
            )

    def spec_for(self, member: str) -> MemberSpec | None:
        for spec in self.member_specs:
            if spec.key == member:
                return spec
        return None


@dataclass(frozen=True)
class InactiveComponent:
    """A component that is declared but not computed."""

    key: str
    label: str
    role: Role
    reason: str
    blocking_requirement: str = ""


@dataclass(frozen=True)
class AssetModuleComponent:
    """An asset-specific transmission module.

    Registered so its role is explicit and enforceable. An asset module is
    ACTIVE NON-VOTING: it computes and conditions interpretation but never
    contributes independent directional evidence, and it does not receive
    voting power until incremental value over the universal core alone has been
    demonstrated -- which no validation has yet done.
    """

    key: str
    label: str
    instrument: str
    role: Role
    rationale: str

    def __post_init__(self) -> None:
        if self.role is not Role.ASSET_SPECIFIC_MODULE:
            raise ValueError(
                f"{self.key}: an asset module must have role ASSET_SPECIFIC_MODULE"
            )


